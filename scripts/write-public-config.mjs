import { writeFile } from "node:fs/promises";

const urlValue = (process.env.SUPABASE_URL || "").trim();
const keyValue = (process.env.SUPABASE_PUBLISHABLE_KEY || "").trim();

if (Boolean(urlValue) !== Boolean(keyValue)) {
  throw new Error("Set both SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY, or leave both empty.");
}
if (urlValue) {
  const parsed = new URL(urlValue);
  if (parsed.protocol !== "https:" || parsed.username || parsed.password) {
    throw new Error("SUPABASE_URL must be an HTTPS URL without embedded credentials.");
  }
  if (!keyValue || keyValue.length > 500 || /\s/.test(keyValue)) {
    throw new Error("SUPABASE_PUBLISHABLE_KEY is not a valid public key value.");
  }
}

const config = {
  url: urlValue.replace(/\/+$/, ""),
  publishableKey: keyValue
};
const source = "/* Generated by GitHub Actions. Contains only public client configuration. */\n" +
  "window.AGUIA_SUPABASE_CONFIG = Object.freeze(" +
  JSON.stringify(config) +
  ");\n";
await writeFile(new URL("../assets/supabase-config.js", import.meta.url), source, { mode: 0o644 });
console.log(urlValue ? "Supabase public configuration generated." : "Supabase is not configured; public queries remain disabled.");
